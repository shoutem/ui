// Lists every mobile-qa extension that has app/themes/style.js and writes src/data/extensionThemes.js.
// The app theme is getTheme() merged with all of these, same as shoutem.rubicon-theme/app/themes/Rubicon.js.
// Imports use bare `shoutem.<ext>/...` specifiers; build.mjs resolves them into mobile-qa/extensions.
import fs from 'fs';
import path from 'path';
import { DATA, EXTENSIONS } from '../paths.mjs';

const names = fs.readdirSync(EXTENSIONS)
  .filter(n => n.startsWith('shoutem.') && fs.existsSync(path.join(EXTENSIONS, n, 'app/themes/style.js')))
  .sort();
const body = names.map(n => `  '${n}': require('${n}/themes/style.js'),`).join('\n');
fs.writeFileSync(path.join(DATA, 'extensionThemes.js'), `// Generated by scripts/scan-themes.mjs. Do not edit by hand.\nexport const extensionThemes = {\n${body}\n};\n`);
console.log(`extensionThemes.js: ${names.length} extensions`);
